#!/usr/bin/env bash
# Regenerates src/d3d.rs from Microsoft's DirectX-Headers (MIT) with bindgen.
set -euo pipefail
commit=faf928dc6feb8b86e9e3d6a39fc5171de7d8ac36
crate=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "${work:?}"' EXIT

git -C "$work" init -q headers
git -C "$work/headers" fetch -q --depth 1 https://github.com/microsoft/DirectX-Headers "$commit"
git -C "$work/headers" checkout -q FETCH_HEAD
cat >"$work/wrapper.hpp" <<'HEADER'
#include <wsl/winadapter.h>
#include <directx/d3dcommon.h>
#include <directx/D3D12TokenizedProgramFormat.hpp>
HEADER

{
	echo "//! Direct3D shader constants, generated by \`scripts/generate-d3d.sh\` from"
	echo "//! <https://github.com/microsoft/DirectX-Headers/tree/$commit>."
	echo "//!"
	sed 's|^|//! |; s| *$||' "$work/headers/LICENSE"
	echo
	echo '#![allow(non_camel_case_types, non_upper_case_globals, dead_code)]'
	echo
	bindgen "$work/wrapper.hpp" \
		--allowlist-type '_?D3D_(SHADER_INPUT_TYPE|RESOURCE_RETURN_TYPE|SRV_DIMENSION|SHADER_INPUT_FLAGS|CBUFFER_TYPE|SHADER_VARIABLE_CLASS|SHADER_VARIABLE_TYPE|SHADER_VARIABLE_FLAGS|NAME|REGISTER_COMPONENT_TYPE)' \
		--allowlist-type 'D3D10_SB_(TOKENIZED_PROGRAM_TYPE|OPCODE_TYPE|RESOURCE_DIMENSION|RESOURCE_RETURN_TYPE|OPERAND_INDEX_DIMENSION|OPERAND_INDEX_REPRESENTATION)' \
		--allowlist-var 'D3D1[01]_SB_.*(MASK|SHIFT|COUNTER)' \
		--default-enum-style consts --no-prepend-enum-name --no-layout-tests --no-doc-comments \
		-- -x c++ -I"$work/headers/include" -I"$work/headers/include/wsl/stubs"
} >"$crate/src/d3d.rs"
rustfmt --edition 2024 "$crate/src/d3d.rs"
